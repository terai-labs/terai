// Generates src/locale.ts from Unicode CLDR data.
// Usage: pnpm --filter @terai/types generate:locales

import { writeFileSync } from 'node:fs'

const CLDR_VERSION = '48.2.0'
const CDN = 'https://cdn.jsdelivr.net/npm'
const OUT = new URL('../src/locale.ts', import.meta.url)

async function load(pkg, file) {
	const res = await fetch(`${CDN}/${pkg}@${CLDR_VERSION}/${file}`)
	if (!res.ok) throw new Error(`${res.status} fetching ${pkg}/${file}`)
	return res.json()
}

const [available, defaultContent, likely, names] = await Promise.all([
	load('cldr-core', 'availableLocales.json'),
	load('cldr-core', 'defaultContent.json'),
	load('cldr-core', 'supplemental/likelySubtags.json'),
	load('cldr-localenames-full', 'main/en/languages.json')
])

const likelySubtags = likely.supplemental.likelySubtags
const languageNames = names.main.en.localeDisplayNames.languages

function parse(tag) {
	const [language, ...rest] = tag.split('-')
	const script = rest.find((part) => /^[A-Z][a-z]{3}$/.test(part))
	const region = rest.find((part) => /^([A-Z]{2}|\d{3})$/.test(part))
	return { language, script, region }
}

// UTS #35 "Add Likely Subtags", enough for language[-script][-region] tags
function maximize(tag) {
	const { language, script, region } = parse(tag)
	const candidates = [
		script && region && `${language}-${script}-${region}`,
		region && `${language}-${region}`,
		script && `${language}-${script}`,
		language
	].filter(Boolean)
	const match = candidates.map((key) => likelySubtags[key]).find(Boolean)
	if (!match) return undefined
	const filled = parse(match)
	return `${language}-${script ?? filled.script}-${region ?? filled.region}`
}

// Every locale CLDR ships, including default-content ones such as en-US
const cldrLocales = [
	...available.availableLocales.full,
	...defaultContent.defaultContent
].filter((tag) => tag !== 'root' && !tag.includes('POSIX'))

const locales = new Set(cldrLocales)

// CLDR spells multi-script locales with their script (zh-Hans-CN, sr-Cyrl-RS),
// but devices and browsers usually send language-region (zh-CN, sr-RS). Add
// the short form when it resolves to the same locale, plus each language's
// most likely region (no-NO).
for (const tag of cldrLocales) {
	const { language, region } = parse(tag)
	if (language === 'und') continue
	const candidates = [region && `${language}-${region}`]
	const likelyRegion = parse(likelySubtags[language] ?? '').region
	if (likelyRegion) candidates.push(`${language}-${likelyRegion}`)

	for (const candidate of candidates.filter(Boolean)) {
		const max = maximize(candidate)
		if (max && max === maximize(tag)) locales.add(candidate)
	}
}

for (const tag of locales) {
	if (Intl.getCanonicalLocales(tag)[0] !== tag) {
		throw new Error(`Not a canonical BCP 47 tag: ${tag}`)
	}
}

const byLanguage = new Map()
for (const tag of [...locales].sort()) {
	const { language } = parse(tag)
	byLanguage.set(language, [...(byLanguage.get(language) ?? []), tag])
}

// Languages CLDR has no English name for yet
const missingNames = {
	apc: 'Levantine Arabic',
	lld: 'Ladin',
	mhn: 'Mòcheno',
	mww: 'Hmong Daw',
	skr: 'Saraiki',
	suz: 'Sunuwar'
}
const lines = []
for (const [language, tags] of byLanguage) {
	const name = languageNames[language] ?? missingNames[language] ?? language
	lines.push(`\t// ${name}`)
	for (const tag of tags) lines.push(`\t| '${tag}'`)
}

writeFileSync(
	OUT,
	`/**
 * BCP 47 Locale Identifiers
 *
 * Every locale in Unicode CLDR v${CLDR_VERSION}, plus the language-region form
 * of locales CLDR spells with a script (e.g. 'zh-CN' for 'zh-Hans-CN').
 * Format follows BCP 47 standard using hyphens (e.g., 'en-US', 'zh-Hans-CN').
 *
 * Generated by scripts/generate-locales.mjs. Do not edit by hand.
 *
 * Structure:
 * - language: ISO 639-1/639-3 language code (e.g., 'en', 'zh')
 * - script: ISO 15924 script code (e.g., 'Hans', 'Latn')
 * - region: ISO 3166-1 alpha-2 country code or UN M.49 region code (e.g., 'US', '419')
 * - variant: Registered variant subtags (e.g., 'valencia', 'tarask')
 *
 * @see https://cldr.unicode.org/
 * @see https://www.ietf.org/rfc/bcp/bcp47.txt
 * @see https://www.iana.org/assignments/language-subtag-registry
 */
export type Locale =
${lines.join('\n')}
`
)

console.log(`Wrote ${locales.size} locales to ${OUT.pathname}`)
